export function resolveMaterial(spool){
 const brand=brandKey(spool.brand),m=normalize(spool.material);
 const material=Object.hasOwn(aliases,m)?aliases[m]:m;
 const family=normalize(spool.family);
 let specific;
 if(brand==='bambu')specific=bambuProfiles[material];
 if(brand==='bambu'&&material==='PLA')return {...bambuProfiles['PLA BASIC'],official:false,brandCategory:true,name:'Bambu PLA Basic（PLA 系列未指定）'};
 if(Object.hasOwn(additional,brand)){
  specific=additional[brand][brandAliases[brand]?.[material]??material];
 }
 if(brand==='sunlu')specific=sunlu[material];
 if(specific)return {...specific,official:true};
 if(brand==='creality'){
  const variants={
   'HYPER PLA':['PLA','190–230','crealityHyperPla'],
   'HYPER PETG':['PETG','220–260','crealityHyperPetg'],
   'CR PETG':['PETG','230–250','crealityPrint'],
   'CR PLA CARBON':['PLA CF','190–220','crealityPrint'],
   'CR ABS':['ABS','245–255','crealityPrint']
  };
  const variant=variants[material];
  if(variant){
   const [kind,nozzleTemp,source]=variant;
   const base=creality[kind];
   return {...base,name:'Creality '+spool.material,official:false,brandCategory:true,nozzleTemp,sources:[...base.sources,source]};
  }
  const category=material==='PLA CF'?material:family;
  const selected=creality[category];
  if(selected){
   return {...selected,official:false,brandCategory:true,nozzleTemp:material===category?selected.nozzleTemp:null};
  }
 }
 const selected=typeExamples[material]??typeExamples[fallbackKeys[material]];
 if(selected)return {...selected,official:false,ams:null,feed:null};
 return {name:spool.material||spool.family,temperature:null,hours:null,dry:'未发布',nozzleTemp:null,chamber:'未发布',enclosure:'未列要求',feed:null,required:false,sources:[],official:false,method:'热风烘箱'};
}

